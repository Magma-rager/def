// Screenshots every screen by injecting run states through the live app (window.__sb).
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const [w = 1194, h = 834, tag = 'ipad'] = process.argv.slice(2);
const OUT = '/tmp/claude-0/shots';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: +w, height: +h }, hasTouch: true });
const errs = [];
p.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message));
p.on('console', (m) => { if (m.type() === 'error' && !m.text().includes('404')) errs.push(m.text()); });
await p.goto('http://localhost:8123/index.html');
await p.waitForTimeout(400);
await p.evaluate(() => { const a = window.__sb; a.meta.tutorialDone = true; a.startRun('beta_badge'); });
await p.waitForTimeout(200);
await p.evaluate(() => { document.querySelector('.dlg-skip')?.click(); });
await p.waitForTimeout(200);
const shot = async (name, fn) => {
  await p.evaluate(fn);
  await p.waitForTimeout(450);
  await p.evaluate(() => document.querySelector('.dlg-skip')?.click());
  await p.waitForTimeout(150);
  await p.screenshot({ path: `${OUT}/${tag}-s-${name}.png` });
};
await shot('reward', () => { const a = window.__sb, r = a.run; const n = r.d.map.nodes[0]; r.d.position = n.id; r.d.pending = r.makeReward(n, 'elite', { scrapBonus: 0 }); a.route(); });
await shot('shop', () => { const a = window.__sb, r = a.run; r.d.scrap = 300; r.d.pending = { type: 'shop', nodeId: 'x', stock: r.makeShop(r.rng('s'), false) }; a.route(); });
await shot('event', () => { const a = window.__sb, r = a.run; r.d.pending = { type: 'event', nodeId: 'x', eventId: 'dev_door', result: null }; a.route(); });
await shot('rest', () => { const a = window.__sb, r = a.run; r.d.pending = { type: 'rest', nodeId: 'x', done: false }; a.route(); });
await shot('surgery', () => { const a = window.__sb, r = a.run; r.d.pending = { type: 'surgery', nodeId: 'x', ops: 0, grafts: ['spark', 'echoing', 'cached'] }; a.route(); });
await shot('treasure', () => { const a = window.__sb, r = a.run; r.d.pending = { type: 'treasure', nodeId: 'x', relics: r.randomRelics(r.rng('t'), 2), taken: false, scrap: 20 }; a.route(); });
await shot('bossprep', () => { const a = window.__sb, r = a.run; r.d.stats.combos = 30; r.d.stats.cashouts = 15; r.d.stats.battles = 6; r.d.pending = { type: 'bossprep', nodeId: 'n1_boss', bossId: 'clockwork_regent', introShown: true, ...r.bossAnalysis() }; a.route(); });
await shot('mutation', () => { const a = window.__sb, r = a.run; r.d.pending = { type: 'mutation', options: ['relay_resonance', 'grinder', 'quick_exit'], taken: null }; a.route(); });
await shot('deck', () => { window.__sb.viewDeck(); });
await shot('select', () => { window.__sb.closeAllModals(); window.__sb.selectCard({ title: 'Upgrade a card', filter: (i) => !i.up, preview: true }); });
await shot('settings', () => { window.__sb.closeAllModals(); window.__sb.openSettings(); });
await shot('howto', () => { window.__sb.closeAllModals(); window.__sb.howToPlay(); });
await shot('museum', () => { window.__sb.closeAllModals(); window.__sb.openMuseum(); });
await shot('results', () => { const a = window.__sb; a.closeAllModals(); a.run.d.bossesDefeated = ['clockwork_regent']; a.endRun('defeat'); });
await shot('results2', () => { document.querySelector('.dlg-skip')?.click(); });
console.log(errs.join('\n') || 'no errors');
await b.close();
