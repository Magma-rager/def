// PWA check: service worker installs, game reloads offline, save persists across reloads.
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1024, height: 768 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://localhost:8124/index.html');
await p.evaluate(() => navigator.serviceWorker.ready);
await p.reload();
await p.waitForTimeout(800);
const controlled = await p.evaluate(() => !!navigator.serviceWorker.controller);
// start a run and take a reward-relevant action so a save exists
await p.getByRole('button', { name: 'New Run' }).click();
await p.getByRole('button', { name: 'Begin' }).click();
await p.waitForTimeout(300);
await p.click('.dlg-skip');
await p.waitForTimeout(200);
const deckBefore = await p.evaluate(() => window.__sb.run.d.deck.length);
await ctx.setOffline(true);
await p.reload();
await p.waitForTimeout(1000);
const title = await p.locator('.logo').count();
const cont = await p.getByRole('button', { name: 'Continue' }).count();
await p.getByRole('button', { name: 'Continue' }).click();
await p.waitForTimeout(500);
const onMap = await p.locator('.map').count();
const deckAfter = await p.evaluate(() => window.__sb.run.d.deck.length);
await p.screenshot({ path: '/tmp/claude-0/shots/offline-continue.png' });
console.log(JSON.stringify({ controlled, offlineTitleRendered: title > 0, continueOffered: cont > 0, continuedToMap: onMap > 0, deckBefore, deckAfter, errs }));
await b.close();
